const appUrl = process.env.APP_URL?.trim();
const secret = process.env.CRON_SECRET?.trim();
if (!appUrl) throw new Error("APP_URL must point to the deployed StanBridge Airways application.");
if (!secret || secret.length < 32) throw new Error("CRON_SECRET must contain at least 32 characters.");
const target = new URL("/api/internal/backup", appUrl);
if (target.protocol !== "https:" && target.hostname !== "localhost" && target.hostname !== "127.0.0.1") throw new Error("Scheduled backup endpoint must use HTTPS.");
const response = await fetch(target, { method: "POST", headers: { Authorization: "Bearer " + secret, Accept: "application/json" }, signal: AbortSignal.timeout(15 * 60 * 1000) });
const result = await response.json().catch(() => ({}));
if (!response.ok) throw new Error("Backup request failed (" + response.status + "): " + (result.error || "unknown error"));
console.log("Backup complete: " + (result.backup?.filename || "created") + " (" + (result.backup?.storageType || "unknown storage") + ")");
